/**
 * Convert 0–1 float channels to '#rrggbb' hex string.
 */
function toHex(r, g, b) {
  return '#' + [r, g, b].map(v =>
    Math.round(v * 255).toString(16).padStart(2, '0')
  ).join('');
}

