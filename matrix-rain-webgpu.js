/**
 * Build a 256-sample inverse-CDF glyph weight LUT as a DataTexture.
 * @param {number[]|null} weights  per-glyph relative weights, or null for uniform
 * @param {number}        glyphCount
 * @returns {THREE.DataTexture}
 */
function buildGlyphWeightLUT(weights, glyphCount) {
  const lut = new Uint8Array(256);
  if (!weights) {
    for (let i = 0; i < 256; i++) lut[i] = Math.floor(i * glyphCount / 256);
  } else {
    const total = weights.reduce((a, b) => a + b, 0);
    const pdf   = weights.map(w => w / total);
    let cumul = 0, glyphIdx = 0;
    for (let i = 0; i < 256; i++) {
      const target = (i + 0.5) / 256;
      while (glyphIdx < glyphCount - 1 && cumul + pdf[glyphIdx] < target) {
        cumul += pdf[glyphIdx++];
      }
      lut[i] = glyphIdx;
    }
  }
  const tex = new THREE.DataTexture(lut, 256, 1, THREE.RedFormat, THREE.UnsignedByteType);
  tex.minFilter = tex.magFilter = THREE.NearestFilter;
  tex.needsUpdate = true;
  return tex;
}

/**
 * Upload the correct weight LUT for charSet into the uniforms node.
 * @param {string} charSet    key from CHAR_SETS (or any string; unknown keys get uniform LUT)
 * @param {number} glyphCount resolved glyph count for this atlas
 * @param {object} uniforms   result of makeUniforms()
 */
function applyGlyphWeightLUT(charSet, glyphCount, uniforms) {
  const w = GLYPH_WEIGHTS[charSet] ?? null;
  uniforms.uGlyphWeightLUT.value = buildGlyphWeightLUT(w, glyphCount);
}

// ── Scene constants ────────────────────────────────────────────────────────
const N_ROWS  = 120;
const CELL_W  = 0.12;
const CELL_H  = 0.08;
const WORLD_H = 16;

// Box-Muller Gaussian random — used for cluster angular jitter
function _gaussRand() {
  const u = 1 - Math.random(); // (0, 1] avoids log(0)
  const v = Math.random();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

// ── MSDF atlas ────────────────────────────────────────────────────────────
function loadMSDF(path) {
  const tex = new THREE.TextureLoader().load(path);
  tex.flipY           = false;
  tex.minFilter       = THREE.LinearMipMapLinearFilter;
  tex.magFilter       = THREE.LinearFilter;
  tex.colorSpace      = THREE.LinearSRGBColorSpace;
  tex.generateMipmaps = true;
  return tex;
}

// ── Instanced buffer geometry ─────────────────────────────────────────────
function buildGeometry({
  speedMin      = 0.8,
  speedMax      = 4.0,
  trailMin      = 0.015,
  trailMax      = 0.050,
  nCols         = 600,
  topology      = 'shell',    // 'shell' | 'ring' | 'curtain' | 'rectangle'
  shellInner    = 3.5,
  shellOuter    = 8.0,
  rectW         = 8.0,        // rectangle topology: half-extent in X
  rectH         = 8.0,        // rectangle topology: half-extent in Z
  clusterCount  = 12,
  clusterSpread = 0.017,      // σ as fraction of full circle; 0.017 ≈ 6°
  radialBias    = 0.0,        // −1 = inner-concentrated, 0 = uniform, +1 = outer-concentrated
} = {}) {
  // Guard against inverted ranges
  const sMin = Math.min(speedMin, speedMax);
  const sMax = Math.max(speedMin, speedMax);
  const tMin = Math.min(trailMin, trailMax);
  const tMax = Math.max(trailMin, trailMax);
  const inner = shellInner;
  const outer = Math.max(shellOuter, inner + 0.1);

  const geom = new THREE.InstancedBufferGeometry();
  const base = new THREE.PlaneGeometry(1, 1);
  geom.index = base.index.clone();
  geom.setAttribute('position', base.getAttribute('position').clone());
  geom.setAttribute('uv',       base.getAttribute('uv').clone());
  base.dispose();

  const total   = nCols * N_ROWS;
  const colBuf  = new Float32Array(total);
  const rowBuf  = new Float32Array(total);
  const colABuf = new Float32Array(total * 4);  // wx, wz, speed, seed
  const colBBuf = new Float32Array(total * 4);  // yOff, scale, alpha, trail

  // Per-instance cluster centers — fresh per buildGeometry() call so each
  // initMatrixRain() gets its own independent pattern.
  const nClusters    = Math.max(1, Math.round(clusterCount));
  const sigma        = Math.max(0.003, clusterSpread) * 2 * Math.PI;  // σ in radians
  const exp_         = Math.pow(2, -radialBias);  // bias=0→exp=1 (uniform)
  const clusterThetas = Array.from({ length: nClusters }, () => Math.random() * Math.PI * 2);

  for (let c = 0; c < nCols; c++) {
    const theta  = clusterThetas[Math.floor(Math.random() * nClusters)] + _gaussRand() * sigma;
    let r        = inner + Math.pow(Math.random(), exp_) * (outer - inner);

    let wx, wz;
    switch (topology) {
      case 'ring': {
        const r_ring = (inner + outer) / 2;
        wx = Math.cos(theta) * r_ring;
        wz = Math.sin(theta) * r_ring;
        break;
      }
      case 'curtain': {
        wx = (Math.random() * 2 - 1) * outer;
        wz = 0;
        break;
      }
      case 'rectangle': {
        wx = (Math.random() * 2 - 1) * rectW;
        wz = (Math.random() * 2 - 1) * rectH;
        break;
      }
      default: // 'shell'
        wx = Math.cos(theta) * r;
        wz = Math.sin(theta) * r;
    }

    // Normalise r for scale gradient — non-shell topologies use a representative radius
    if (topology === 'ring')    r = (inner + outer) / 2;
    if (topology === 'curtain') r = (inner + outer) / 2;
    if (topology === 'rectangle') r = Math.min(Math.max(rectW, rectH), Math.max(inner, Math.sqrt(wx * wx + wz * wz)));

    const yOff  = (Math.random() - 0.5) * WORLD_H;
    const sr    = Math.random();
    const speed = sMin + sr * sr * (sMax - sMin);  // log-biased over range
    const seed  = Math.random();
    const t     = (r - inner) / (outer - inner);           // 0 = inner (close), 1 = outer (far)
    const scale = (1.45 - t * 0.95) + (Math.random() - 0.5) * 0.2;
    const alpha = 0.18 + Math.random() * 0.72;
    const trail = tMin + Math.random() * (tMax - tMin);

    for (let row = 0; row < N_ROWS; row++) {
      const idx = c * N_ROWS + row;
      colBuf[idx] = c;
      rowBuf[idx] = row;
      const i4 = idx * 4;
      colABuf[i4]     = wx;
      colABuf[i4 + 1] = wz;
      colABuf[i4 + 2] = speed;
      colABuf[i4 + 3] = seed;
      colBBuf[i4]     = yOff;
      colBBuf[i4 + 1] = scale;
      colBBuf[i4 + 2] = alpha;
      colBBuf[i4 + 3] = trail;
    }
  }

  geom.setAttribute('aColIdx', new THREE.InstancedBufferAttribute(colBuf,  1));
  geom.setAttribute('aRowIdx', new THREE.InstancedBufferAttribute(rowBuf,  1));
  geom.setAttribute('aColA',   new THREE.InstancedBufferAttribute(colABuf, 4));
  geom.setAttribute('aColB',   new THREE.InstancedBufferAttribute(colBBuf, 4));
  geom.instanceCount = total;
  return geom;
}

